"""Refresh the offline gallery's source text. Standard library only."""
import json
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MAIN = ROOT / "android/app/src/main"
PRESENTATION = MAIN / "java/me/kavishdevar/librepods/presentation"


def clean(text):
    return text.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"').strip()


strings = {
    item.attrib["name"]: clean("".join(item.itertext()))
    for item in ET.parse(MAIN / "res/values/strings.xml").getroot()
    if item.tag == "string"
}
privacy = (PRESENTATION / "screens/onboarding/PrivacyPolicyPage.kt").read_text()
privacy_text = [clean(text) for text in re.findall(r'Text\(\s*(?:text\s*=\s*)?"((?:\\.|[^"\\])*)"', privacy)]
libraries = json.loads((MAIN / "res/raw/aboutlibraries.json").read_text())
route_source = re.sub(r'//[^\n]*', '', (PRESENTATION / "navigation/Screen.kt").read_text())
routes = re.findall(r'data (?:object|class) (\w+)', route_source)
data = {
    "strings": strings,
    "privacy": privacy_text,
    "libraries": libraries["libraries"],
    "routes": routes,
    "commit": subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip(),
}
(HERE / "source-data.js").write_text(
    "// Generated by generate-data.py from this checkout. Do not edit by hand.\n"
    + "window.SOURCE_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
)
print(f"Generated {len(strings)} strings, {len(routes)} routes, {len(data['libraries'])} libraries.")
